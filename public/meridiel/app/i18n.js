export function normalizeLocale(value) {
  const v = String(value || "").toLowerCase();
  if (!v) return null;
  if (v.startsWith("zh")) return "zh-Hant";
  if (v.startsWith("ja")) return "ja";
  if (v.startsWith("en")) return "en";
  return null;
}

// Explicit choice (localStorage) wins; otherwise the first browser language
// we support; English is the final fallback.
export function detectLocale(storage, languages) {
  try {
    const saved = storage && storage.getItem(STORAGE_KEY);
    if (LOCALES.includes(saved)) return saved;
  } catch (e) { /* storage blocked — fall through to the browser language */ }
  for (const lang of languages || []) {
    const hit = normalizeLocale(lang);
    if (hit) return hit;
  }
  return "en";
}

let current = typeof navigator !== "undefined"
  ? detectLocale(typeof localStorage !== "undefined" ? localStorage : null, navigator.languages || [navigator.language])
  : "en";

export function getLocale() { return current; }

export function setLocale(locale) {
  if (!LOCALES.includes(locale)) return current;
  current = locale;
  try { localStorage.setItem(STORAGE_KEY, locale); } catch (e) { /* not persisted — fine */ }
  if (typeof document !== "undefined") document.documentElement.lang = locale;
  return current;
}

export function translate(locale, key, vars) {
  const table = MESSAGES[locale] || MESSAGES.en;
  let text = table[key];
  if (text == null) text = MESSAGES.en[key];
  if (text == null) return key;
  if (vars) {
    text = text.replace(/\{(\w+)\}/g, (m, name) => (vars[name] == null ? m : String(vars[name])));
  }
  return text;
}

export function t(key, vars) { return translate(current, key, vars); }

// BCP-47 tag for Intl formatters (dates, numbers).
export function intlLocale() {
  return current === "zh-Hant" ? "zh-TW" : current === "ja" ? "ja-JP" : "en-US";
}

export function fmtNum(n, decimals) {
  const value = Number(n) || 0;
  return value.toLocaleString(intlLocale(), decimals
    ? { minimumFractionDigits: decimals, maximumFractionDigits: decimals }
    : { maximumFractionDigits: 0 });
}
